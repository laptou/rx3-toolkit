"""Static guards for the CHARIZARD2 module."""

from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
MODULE = (ROOT / "module.sh").read_text()
MANIFEST = json.loads((ROOT / "manifest.json").read_text())
FEATURE = (ROOT / "rx3_charizard2_feature.h").read_text()
LABELS = (ROOT / "rx3_charizard2_labels.h").read_text()
HOOK = (ROOT.parents[1] / "core/1.19/rx3_core_hook.c").read_text()
SPRITES = json.loads((ROOT.parents[1] / "sprites/1.19/manifest.json").read_text())


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


require(
    "module_begin charizard2 charizard2" in MODULE
    and MANIFEST["id"] == "charizard2"
    and MANIFEST["order"] == 110
    and MANIFEST["requires"] == ["core"]
    and MANIFEST["conflicts"] == ["sprites"]
    and "charizard2" in SPRITES["conflicts"],
    "charizard2 requires the core and conflicts with sprites, both ways",
)
require(
    'export RX3_CHARIZARD_PACK="$USB/RX3_SPRITES/charizard.rx3spr"' in MODULE
    and "export RX3_CHARIZARD2=1" in MODULE
    and MODULE.index("charizard.rx3spr is missing") < MODULE.index("export RX3_CHARIZARD2=1")
    and "request_rbp_restart" in MODULE
    and 'getenv("RX3_CHARIZARD2")' in FEATURE
    and 'getenv("RX3_CHARIZARD_PACK")' in FEATURE,
    "without charizard.rx3spr the flag stays unset and TRANS stays stock",
)
require(
    "#define BEAT_FX_TRANS 2" in FEATURE
    and "#define BEAT_FX_UI_TRANS 9" in FEATURE
    and "#define BEAT_FX_DISPLAY_TRANS 3" in FEATURE
    and "rx3_beat_fx_owned(fields, BEAT_FX_TRANS)" in FEATURE
    and "rx3_beat_fx_on(fields, BEAT_FX_TRANS)" in FEATURE
    and "(fields + 0xe8u)" in FEATURE
    and "(fields + 0x00u)" in FEATURE,
    "TRANS is engine type 2, ui type 9, display 3; depth is +0xe8 and "
    "channel is +0x00",
)
require(
    "TRANS_CAPTION_FIRST 0x1469u" in FEATURE
    and "TRANS_CAPTION_LAST 0x146cu" in FEATURE
    and "TRANS_SELECT_FIRST 0x15c2u" in FEATURE
    and "TRANS_SELECT_LAST 0x15c4u" in FEATURE
    and "rx3_relabel_image(image_id, &cz_label_caption)" in FEATURE
    and "generated by tools/rx3_assets/build_masks.py" in LABELS,
    "TRANS captions and select tiles read CHARIZARD",
)
require(
    "*y = WAVE_TOP + (WAVE_STRIP - height) / 2;" in FEATURE
    and "*y = WAVE_TOP + WAVE_STRIP + (WAVE_STRIP - height) / 2;" in FEATURE
    and "*y = WAVE_TOP + WAVE_STRIP - height / 2;" in FEATURE
    and "CZ_BASE_HEIGHT ((WAVE_STRIP * 9) / 10)" in FEATURE
    and "RX3_GR_ON_TOP" in FEATURE,
    "channel 0 is the top strip, channel 1 the bottom, anything else the seam",
)
require(
    "buffer[" not in FEATURE
    and "(void)buffer;" in FEATURE
    and "return 1;" in FEATURE,
    "while TRANS is owned the block is left untouched",
)
require(
    "rx3_sprite_fps_frame" in FEATURE
    and "rx3_sprite_checksum" in FEATURE
    and "header->format_byte != 2u" in FEATURE
    and "header->bpp != 8u" in FEATURE
    and "CZ_EDGE_LIMIT 256u" in FEATURE
    and "CZ_FILE_LIMIT (4u * 1024u * 1024u)" in FEATURE
    and "header->anchor != 1u && header->anchor != 2u" in FEATURE,
    "the pack is the sprites encoding, animated on its fps clock",
)
require(
    "#define RUNTIME_FEATURE_COUNT 7u" in HOOK
    and '#include "../../charizard2/1.19/rx3_charizard2_feature.h"' in HOOK
    and ".beat_fx_operate = charizard2_feature_beat_fx_operate," in HOOK
    and ".image_swap = charizard2_feature_image_swap," in HOOK
    and ".after_image = charizard2_feature_after_image," in HOOK
    and "charizard2_feature_beat_fx_beat" not in HOOK
    and "charizard2_feature_beat_fx_time" not in HOOK,
    "the performance core owns CHARIZARD2, and BEAT and TIME stay stock",
)

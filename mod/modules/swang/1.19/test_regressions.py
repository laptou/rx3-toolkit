"""Static guards for the Swang module, all of them measured facts."""

from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
MODULE = (ROOT / "module.sh").read_text()
MANIFEST = json.loads((ROOT / "manifest.json").read_text())
FEATURE = (ROOT / "rx3_swang_feature.h").read_text()
DSP = (ROOT / "rx3_swang_dsp.h").read_text()
LABELS = (ROOT / "rx3_swang_labels.h").read_text()
HOOK = (ROOT.parents[1] / "core/1.19/rx3_core_hook.c").read_text()


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


require(
    "module_begin swang swang" in MODULE
    and MANIFEST["runtime_directory"] == "swang",
    "the orchestrator loads this module under the id and namespace it declares",
)
require(
    '[ -r "$CORE_OBJECT" ]' in MODULE and 'getenv("RX3_SWANG")' in FEATURE,
    "the module declines without the core and the feature gates on its flag",
)
require(
    "install_hook(" not in FEATURE
    and ".beat_fx_operate = swang_feature_beat_fx_operate," in HOOK
    and ".beat_fx_beat = swang_feature_beat_fx_beat," in HOOK
    and ".beat_fx_time = swang_feature_beat_fx_time," in HOOK
    and ".playhead = swang_feature_playhead," in HOOK
    and "original_beat_fx_time_event && rx3_deck_tap_ready()" in FEATURE,
    "the core's broker and deck tap own every hook; the feature does not "
    "start without them",
)
require(
    "#define BEAT_FX_SPIRAL 7" in FEATURE
    and "#define BEAT_FX_UI_SPIRAL 3" in FEATURE
    and "#define BEAT_FX_DISPLAY_SPIRAL 5" in FEATURE
    and "rx3_beat_fx_owned(fields, BEAT_FX_SPIRAL)" in FEATURE
    and "rx3_beat_fx_on(fields, BEAT_FX_SPIRAL)" in FEATURE,
    "spiral is engine type 7, ui type 3 and display type 5; the broker's "
    "ownership rule decides when stock is skipped and when it swings",
)
require(
    "SPIRAL_CAPTION_FIRST 0x1465u" in FEATURE
    and "SPIRAL_CAPTION_LAST 0x1468u" in FEATURE
    and "SPIRAL_SELECT_FIRST 0x15bfu" in FEATURE
    and "SPIRAL_SELECT_LAST 0x15c1u" in FEATURE
    and "rx3_relabel_image(image_id, &sw_label_caption)" in FEATURE
    and "generated by tools/rx3_assets/build_masks.py" in LABELS
    and "rx3_swang_labels.h" in MANIFEST["build_files"],
    "spiral's captions and select tiles read SWANG",
)
require(
    "0x011497d0" in FEATURE
    and "(engine + 0x5cu)" in FEATURE
    and "(sync + 0x1cu)" in FEATURE
    and "(sync + 0x20u)" in FEATURE
    and "(sync + 0x08u)" in FEATURE,
    "the tempo master is PlayEngine's SyncMaster: +0x8, or +0x20 while "
    "+0x1c overrides it",
)
require(
    "fields[0xe9u]" in FEATURE,
    "TIME stays stock while it is the beat fx bpm adjust",
)
require(
    "(fields + 0xe8u)" in FEATURE and "(effect + 0x3cu)" not in FEATURE,
    "DEPTH is the manager's pending value, because the skipped "
    "operateBeatEffect is what copies it onto the effect; ON is the "
    "requested type, not the effect's flag",
)
require(
    "#define SW_RING 65536u" in DSP,
    "the ring holds a quarter of a two-beat pair at 40 bpm plus the phase "
    "search",
)
require(
    "#define SW_LAG_NEAR 96u" in DSP
    and "#define SW_LAG_WIDE 441u" in DSP
    and "sw_onset(state" in DSP
    and "(int)(pair_beats * 2.0f + 0.5f)" in FEATURE,
    "each sixteenth is pinned by one splice: within 2 ms of the grid when a "
    "hit is there, anywhere in half a 50 hz period when not; the feature "
    "tells the dsp how many sixteenths a note holds",
)
require(
    "#include <math.h>" not in FEATURE and "#include <math.h>" not in DSP
    and "%" not in FEATURE.split("static int swang_feature_beat_fx_time")[1]
    .split("static void swang_feature_beat_fx_info")[0],
    "the hook links no libm and no signed division helper",
)

print("Swang regression guards: OK")

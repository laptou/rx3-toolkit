"""Render label text to coverage masks in a C header, at build time.

A mask carries lettering only: sixteen coverage levels, no colour. The player
lays it over a copy of one of Pioneer's own images, sized and coloured from that
image, so a relabelled caption keeps the stock ground, ink and box without this
repository ever holding Pioneer's artwork or knowing its dimensions.

Every mask in one header shares one vertical box (the union of the ink of all
its labels), so labels that swap in place keep one baseline.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

from build_labels import COVERAGE_LEVELS, load_font


def render_masks(labels: list[tuple[str, str]], font) -> list[tuple[str, str, int, int, list[int]]]:
    from PIL import Image, ImageDraw

    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    boxes = [probe.textbbox((0, 0), text, font=font) for _, text in labels]
    top = min(box[1] for box in boxes)
    bottom = max(box[3] for box in boxes)
    steps = COVERAGE_LEVELS - 1
    masks = []
    for (name, text), (left, _, right, _) in zip(labels, boxes):
        width, height = right - left, bottom - top
        image = Image.new("L", (width, height), 0)
        ImageDraw.Draw(image).text((-left, -top), text, font=font, fill=255)
        coverage = [round(value / 255 * steps) for value in image.tobytes()]
        masks.append((name, text, width, height, coverage))
    return masks


def header(masks, prefix: str, guard: str) -> str:
    lines = [
        "/* SPDX-License-Identifier: MPL-2.0",
        " * generated by tools/rx3_assets/build_masks.py; do not edit.",
        f" * coverage 0..{COVERAGE_LEVELS - 1}, row-major. */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
    ]
    for name, text, width, height, coverage in masks:
        symbol = f"{prefix}_{name}"
        lines.append(f"/* {text} */")
        lines.append(f"static const uint8_t {symbol}_coverage[{width * height}] = {{")
        for row in range(height):
            cells = coverage[row * width:(row + 1) * width]
            lines.append("    " + ",".join(str(cell) for cell in cells) + ",")
        lines.append("};")
        lines.append(
            f"static const struct rx3_label_mask {symbol} = "
            f"{{ {width}u, {height}u, {symbol}_coverage }};"
        )
        lines.append("")
    lines.append(f"#endif /* {guard} */")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=pathlib.Path, required=True)
    parser.add_argument("--prefix", required=True, help="C symbol prefix")
    parser.add_argument("--font", help="TrueType path; the face is a judgement call")
    parser.add_argument("--font-size", type=int, default=22)
    parser.add_argument("--font-index", type=int, default=0)
    parser.add_argument("labels", nargs="+", metavar="NAME=TEXT")
    arguments = parser.parse_args(argv)

    labels = []
    for entry in arguments.labels:
        name, separator, text = entry.partition("=")
        if not separator or not re.fullmatch(r"[a-z0-9_]+", name) or not text:
            parser.error(f"{entry!r}: expected NAME=TEXT with a lowercase C name")
        labels.append((name, text))
    try:
        import PIL  # noqa: F401
    except ImportError:
        print("Pillow is required to regenerate label masks", file=sys.stderr)
        return 2

    font = load_font(arguments.font, arguments.font_size, arguments.font_index)
    masks = render_masks(labels, font)
    guard = re.sub(r"[^A-Z0-9]", "_", arguments.output.name.upper())
    arguments.output.write_text(header(masks, arguments.prefix, guard), encoding="utf-8")
    print(f"{len(masks)} masks -> {arguments.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
